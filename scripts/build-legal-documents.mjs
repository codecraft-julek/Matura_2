import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { legalDocuments, withdrawalForm } from '../src/content/legal/documents.js'
import { standaloneLegalDocument, legalStyles } from '../src/content/legal/render.js'

const root = join(import.meta.dirname, '..')
const output = join(root, 'public', 'dokumenty')
const origin = (process.env.VITE_SITE_URL ?? (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : 'http://localhost:5173')).replace(/\/+$/, '')
mkdirSync(output, { recursive: true })
for (const doc of legalDocuments) writeFileSync(join(output, `${doc.id}-${doc.version}.html`), standaloneLegalDocument(doc, origin))
writeFileSync(join(output, 'formularz-odstapienia.txt'), withdrawalForm)
writeFileSync(join(root, 'src/styles/legal.css'), `/* Generated by scripts/build-legal-documents.mjs; edit src/content/legal/render.js. */\n${legalStyles}`)
console.log('Generated versioned legal documents, withdrawal form, and legal styles.')
